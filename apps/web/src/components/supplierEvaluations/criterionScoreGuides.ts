export function getCriterionScoreGuide(code: string | null | undefined): CriterionScoreGuide | null {
  if (!code) return null;
  if (code === GENERAL_SCORE_GUIDE_CODE || GENERAL_GUIDE_CRITERION_CODES.has(code)) {
    const guide = CRITERION_SCORE_GUIDES[code] ?? CRITERION_SCORE_GUIDES[GENERAL_SCORE_GUIDE_CODE];
    return guide ?? null;
  }
  return CRITERION_SCORE_GUIDES[code] ?? null;
}

/** Уровни шкалы для отображения: от 5 к 1. */
export function orderedGuideLevels(guide: CriterionScoreGuide): CriterionScoreLevelGuide[] {
  return [...guide.levels].sort((left, right) => right.score - left.score);
}

/** Все критерии матрицы Excel в порядке отображения. */
export function listMatrixCriterionScoreGuides(): CriterionScoreGuide[] {
  return CRITERION_SCORE_GUIDE_ORDER.map((code) => CRITERION_SCORE_GUIDES[code]).filter(
    (guide): guide is CriterionScoreGuide => guide != null,
  );
}

/** Целые уровни матрицы, к которым «примыкает» оценка (для 3.5 → 3 и 4). */
export function adjacentScoreLevels(score: number): CriterionScoreLevelValue[] {
  if (!Number.isFinite(score)) return [];
  const clamped = Math.min(5, Math.max(1, score));
  const floor = Math.floor(clamped) as CriterionScoreLevelValue;
  const ceil = Math.ceil(clamped) as CriterionScoreLevelValue;
  if (floor === ceil) return [floor];
  return [floor, ceil];
}
