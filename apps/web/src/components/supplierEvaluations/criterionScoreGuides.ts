/** Описания баллов по критериям (SQA-TEM-003, матрица оценки поставщика). */

export type CriterionScoreLevelValue = 1 | 2 | 3 | 4 | 5;

export type CriterionScoreLevelGuide = {
  score: CriterionScoreLevelValue;
  label: string;
  /** Пункты описания; пустая строка не допускается. */
  lines: string[];
};

export type CriterionScoreGuide = {
  code: string;
  /** Полное название из матрицы (может отличаться от короткого имени в UI). */
  title: string;
  levels: CriterionScoreLevelGuide[];
};

const LEVEL_LABELS: Record<CriterionScoreLevelValue, string> = {
  5: 'Превосходит ожидания',
  4: 'Хорошо',
  3: 'Средне',
  2: 'Ниже среднего',
  1: 'Слабо',
};

function level(score: CriterionScoreLevelValue, lines: string[]): CriterionScoreLevelGuide {
  return { score, label: LEVEL_LABELS[score], lines };
}

function generalLevel(score: CriterionScoreLevelValue, description: string): CriterionScoreLevelGuide {
  return { score, label: String(score), lines: [description] };
}

